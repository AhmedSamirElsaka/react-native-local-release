import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import {
  assertOwnerOnlyReadable,
  copyFileSecure,
  ensureSecretDir,
  exists,
  isSymlink,
  writeSecretText,
} from './fs.js';
import { rejectControlChars, resolveWithinRoot, toPosixRelative } from './paths.js';
import { ask, askSecret, askYesNo } from './prompt.js';
import type { CredentialProviderKind } from './types.js';
import type readline from 'node:readline/promises';

export type CredentialValues = {
  ASC_KEY_ID: string;
  ASC_ISSUER_ID: string;
  ASC_KEY_FILEPATH: string;
  APPLE_ID: string;
  PLAY_JSON_KEY_PATH: string;
  MYAPP_UPLOAD_STORE_FILE: string;
  MYAPP_UPLOAD_KEY_ALIAS: string;
  MYAPP_UPLOAD_STORE_PASSWORD: string;
  MYAPP_UPLOAD_KEY_PASSWORD: string;
};

function escapeEnvValue(value: string): string {
  rejectControlChars(value, 'credential value');
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function writeEnvFile(filePath: string, values: CredentialValues): void {
  const lines = [
    '# Generated by react-native-local-release. Never commit.',
    `ASC_KEY_ID=${escapeEnvValue(values.ASC_KEY_ID)}`,
    `ASC_ISSUER_ID=${escapeEnvValue(values.ASC_ISSUER_ID)}`,
    `ASC_KEY_FILEPATH=${escapeEnvValue(values.ASC_KEY_FILEPATH)}`,
    values.APPLE_ID ? `APPLE_ID=${escapeEnvValue(values.APPLE_ID)}` : '# APPLE_ID=',
    `PLAY_JSON_KEY_PATH=${escapeEnvValue(values.PLAY_JSON_KEY_PATH)}`,
    `MYAPP_UPLOAD_STORE_FILE=${escapeEnvValue(values.MYAPP_UPLOAD_STORE_FILE)}`,
    `MYAPP_UPLOAD_KEY_ALIAS=${escapeEnvValue(values.MYAPP_UPLOAD_KEY_ALIAS)}`,
    `MYAPP_UPLOAD_STORE_PASSWORD=${escapeEnvValue(values.MYAPP_UPLOAD_STORE_PASSWORD)}`,
    `MYAPP_UPLOAD_KEY_PASSWORD=${escapeEnvValue(values.MYAPP_UPLOAD_KEY_PASSWORD)}`,
    '',
  ];
  writeSecretText(filePath, lines.join('\n'));
}

function writeKeystoreProperties(filePath: string, values: CredentialValues): void {
  const lines = [
    '# Generated by react-native-local-release. Never commit.',
    `MYAPP_UPLOAD_STORE_FILE=${values.MYAPP_UPLOAD_STORE_FILE}`,
    `MYAPP_UPLOAD_KEY_ALIAS=${values.MYAPP_UPLOAD_KEY_ALIAS}`,
    `MYAPP_UPLOAD_STORE_PASSWORD=${values.MYAPP_UPLOAD_STORE_PASSWORD}`,
    `MYAPP_UPLOAD_KEY_PASSWORD=${values.MYAPP_UPLOAD_KEY_PASSWORD}`,
    '',
  ];
  for (const value of Object.values(values)) {
    rejectControlChars(value, 'keystore property');
  }
  writeSecretText(filePath, lines.join('\n'));
}

function vaultRoot(): string {
  return path.join(os.homedir(), '.rn-local-release', 'vault');
}

function projectVaultDir(projectRoot: string): string {
  const slug = path.basename(path.resolve(projectRoot)).replace(/[^\w.-]+/g, '_');
  return path.join(vaultRoot(), slug);
}

function keychainAvailable(): boolean {
  if (process.platform !== 'darwin') return false;
  const result = spawnSync('security', ['help'], { encoding: 'utf8' });
  return result.status === 0;
}

function keychainSet(service: string, account: string, secret: string): void {
  spawnSync(
    'security',
    ['add-generic-password', '-U', '-s', service, '-a', account, '-w', secret],
    { encoding: 'utf8', stdio: 'ignore' },
  );
}

function keychainGet(service: string, account: string): string | null {
  const result = spawnSync(
    'security',
    ['find-generic-password', '-s', service, '-a', account, '-w'],
    { encoding: 'utf8' },
  );
  if (result.status !== 0) return null;
  return (result.stdout || '').trim() || null;
}

function keychainDelete(service: string, account: string): void {
  spawnSync('security', ['delete-generic-password', '-s', service, '-a', account], {
    stdio: 'ignore',
  });
}

function assertCredentialSource(projectRoot: string, sourcePath: string, allowExternal: boolean): string {
  if (isSymlink(sourcePath) || (exists(sourcePath) && isSymlink(sourcePath))) {
    throw new Error(`Refusing symlink credential source: ${sourcePath}`);
  }
  const absolute = path.isAbsolute(sourcePath)
    ? path.resolve(sourcePath)
    : path.resolve(projectRoot, sourcePath);
  if (!exists(absolute)) {
    throw new Error(`Credential file not found: ${absolute}`);
  }
  if (!allowExternal) {
    return resolveWithinRoot(projectRoot, sourcePath);
  }
  return fs.realpathSync(absolute);
}

function assertNotGitTracked(projectRoot: string, relativePath: string): void {
  const checkIgnore = spawnSync('git', ['check-ignore', '-q', relativePath], {
    cwd: projectRoot,
    encoding: 'utf8',
  });
  const lsFiles = spawnSync('git', ['ls-files', '--error-unmatch', relativePath], {
    cwd: projectRoot,
    encoding: 'utf8',
  });
  if (lsFiles.status === 0) {
    throw new Error(
      `Refusing to write credentials: ${relativePath} is tracked by git. Untrack it first.`,
    );
  }
  // If git repo and path is not ignored, warn by failing closed for secret dirs.
  if (
    exists(path.join(projectRoot, '.git')) &&
    checkIgnore.status !== 0 &&
    (relativePath.startsWith('secrets/') ||
      relativePath.includes('keystore.properties') ||
      relativePath.includes('fastlane/.env'))
  ) {
    throw new Error(
      `Refusing to write credentials: ${relativePath} is not gitignored. Update .gitignore first.`,
    );
  }
}

export function defaultCredentialProvider(): CredentialProviderKind {
  return keychainAvailable() ? 'keychain' : 'file';
}

export async function setupCredentialsInteractively(
  rl: readline.Interface,
  projectRoot: string,
  options: {
    dryRun?: boolean;
    provider?: CredentialProviderKind;
    allowExternalPaths?: boolean;
    /** Test/CI hook — never used for production prompts by default. */
    readSecret?: (question: string) => Promise<string>;
  } = {},
): Promise<{ configured: boolean; provider: CredentialProviderKind }> {
  const readSecret = options.readSecret || askSecret;
  const provider = options.provider || defaultCredentialProvider();
  const allowExternal = options.allowExternalPaths === true;
  console.log('');
  console.log('Credential setup');
  console.log('----------------');
  console.log(`Provider: ${provider}`);
  console.log('Passwords are hidden. Secrets are never printed after entry.');
  console.log('');

  const wantApple = await askYesNo(rl, 'Configure Apple App Store Connect API credentials?', true);
  let apple: { keyId: string; issuerId: string; keyPath: string; appleId: string } | null = null;
  if (wantApple) {
    const keyId = await ask(rl, 'ASC Key ID');
    const issuerId = await ask(rl, 'ASC Issuer ID');
    const keyPath = await ask(rl, 'Path to AuthKey_XXXXXX.p8');
    const appleId = await ask(rl, 'Optional Apple ID email (Enter to skip)', '');
    if (!keyId || !issuerId || !keyPath) {
      throw new Error('ASC_KEY_ID, ASC_ISSUER_ID, and .p8 path are required.');
    }
    apple = { keyId, issuerId, keyPath, appleId };
  }

  const wantPlay = await askYesNo(rl, 'Configure Google Play service-account credentials?', true);
  let play: { jsonPath: string } | null = null;
  if (wantPlay) {
    const jsonPath = await ask(rl, 'Path to Play service-account JSON');
    if (!jsonPath) throw new Error('Play JSON path is required.');
    play = { jsonPath };
  }

  const wantAndroid = await askYesNo(rl, 'Configure Android upload keystore?', true);
  let android: {
    storeFile: string;
    alias: string;
    storePassword: string;
    keyPassword: string;
  } | null = null;
  if (wantAndroid) {
    const storeFile = await ask(rl, 'Path to upload keystore', 'android/app/keystore.jks');
    const alias = await ask(rl, 'Key alias', 'key0');
    const storePassword = await readSecret('Keystore password');
    const keyPasswordRaw = await readSecret('Key password (Enter to reuse keystore password)');
    const keyPassword = keyPasswordRaw || storePassword;
    if (!storeFile || !alias || !storePassword || !keyPassword) {
      throw new Error('Keystore path, alias, and passwords are required.');
    }
    android = { storeFile, alias, storePassword, keyPassword };
  }

  if (!apple && !play && !android) {
    console.log('Skipped credential setup.');
    return { configured: false, provider };
  }
  if (options.dryRun) {
    console.log('Dry run: would write credentials via selected provider.');
    return { configured: true, provider };
  }

  const previousUmask = process.umask(0o077);
  try {
    ensureSecretDir(path.join(projectRoot, 'secrets'));
    ensureSecretDir(path.join(projectRoot, 'fastlane'));
    ensureSecretDir(path.join(projectRoot, 'android'));
    ensureSecretDir(projectVaultDir(projectRoot));

    const values: CredentialValues = {
      ASC_KEY_ID: '',
      ASC_ISSUER_ID: '',
      ASC_KEY_FILEPATH: '',
      APPLE_ID: '',
      PLAY_JSON_KEY_PATH: '',
      MYAPP_UPLOAD_STORE_FILE: 'keystore.jks',
      MYAPP_UPLOAD_KEY_ALIAS: 'key0',
      MYAPP_UPLOAD_STORE_PASSWORD: '',
      MYAPP_UPLOAD_KEY_PASSWORD: '',
    };

    if (apple) {
      const source = assertCredentialSource(projectRoot, apple.keyPath, allowExternal);
      const destName = `AuthKey_${apple.keyId}.p8`;
      const vaultDest = path.join(projectVaultDir(projectRoot), destName);
      copyFileSecure(source, vaultDest, 0o600);
      if (provider === 'file') {
        const projectDest = path.join(projectRoot, 'secrets', destName);
        assertNotGitTracked(projectRoot, `secrets/${destName}`);
        copyFileSecure(source, projectDest, 0o600);
        values.ASC_KEY_FILEPATH = `secrets/${destName}`;
      } else {
        values.ASC_KEY_FILEPATH = vaultDest;
        keychainSet(`rn-local-release:${path.basename(projectRoot)}`, 'ASC_KEY_ID', apple.keyId);
        keychainSet(
          `rn-local-release:${path.basename(projectRoot)}`,
          'ASC_ISSUER_ID',
          apple.issuerId,
        );
      }
      values.ASC_KEY_ID = apple.keyId;
      values.ASC_ISSUER_ID = apple.issuerId;
      values.APPLE_ID = apple.appleId;
    }

    if (play) {
      const source = assertCredentialSource(projectRoot, play.jsonPath, allowExternal);
      const destName = 'play-store-service-account.json';
      const vaultDest = path.join(projectVaultDir(projectRoot), destName);
      copyFileSecure(source, vaultDest, 0o600);
      if (provider === 'file') {
        const projectDest = path.join(projectRoot, 'secrets', destName);
        assertNotGitTracked(projectRoot, `secrets/${destName}`);
        copyFileSecure(source, projectDest, 0o600);
        values.PLAY_JSON_KEY_PATH = `secrets/${destName}`;
      } else {
        values.PLAY_JSON_KEY_PATH = vaultDest;
      }
    }

    if (android) {
      const source = assertCredentialSource(projectRoot, android.storeFile, allowExternal);
      const base = path.basename(source);
      const appDest = path.join(projectRoot, 'android', 'app', base);
      if (path.resolve(source) !== path.resolve(appDest)) {
        copyFileSecure(source, appDest, 0o600);
      } else {
        // Already in place — harden mode instead of failing on default umask 0644.
        fs.chmodSync(appDest, 0o600);
        assertOwnerOnlyReadable(appDest);
      }
      values.MYAPP_UPLOAD_STORE_FILE = base;
      values.MYAPP_UPLOAD_KEY_ALIAS = android.alias;
      values.MYAPP_UPLOAD_STORE_PASSWORD = android.storePassword;
      values.MYAPP_UPLOAD_KEY_PASSWORD = android.keyPassword;
      if (provider === 'keychain') {
        const service = `rn-local-release:${path.basename(projectRoot)}`;
        keychainSet(service, 'MYAPP_UPLOAD_STORE_PASSWORD', android.storePassword);
        keychainSet(service, 'MYAPP_UPLOAD_KEY_PASSWORD', android.keyPassword);
        keychainSet(service, 'MYAPP_UPLOAD_KEY_ALIAS', android.alias);
        // Still write keystore.properties without passwords for Gradle filename/alias only.
        writeKeystoreProperties(path.join(projectRoot, 'android', 'keystore.properties'), {
          ...values,
          MYAPP_UPLOAD_STORE_PASSWORD: '',
          MYAPP_UPLOAD_KEY_PASSWORD: '',
        });
      } else {
        assertNotGitTracked(projectRoot, 'android/keystore.properties');
        writeKeystoreProperties(
          path.join(projectRoot, 'android', 'keystore.properties'),
          values,
        );
      }
    }

    // Always write a non-secret reference env for Fastlane paths; passwords only for file provider.
    assertNotGitTracked(projectRoot, 'fastlane/.env');
    if (provider === 'file') {
      writeEnvFile(path.join(projectRoot, 'fastlane', '.env'), values);
    } else {
      writeEnvFile(path.join(projectRoot, 'fastlane', '.env'), {
        ...values,
        MYAPP_UPLOAD_STORE_PASSWORD: '',
        MYAPP_UPLOAD_KEY_PASSWORD: '',
      });
      // Materialize passwords into env from keychain at runtime via doctor/release helpers.
      if (android) {
        const service = `rn-local-release:${path.basename(projectRoot)}`;
        // Ensure we can read them back
        keychainGet(service, 'MYAPP_UPLOAD_STORE_PASSWORD');
      }
    }

    console.log('');
    console.log('Credentials configured.');
    console.log(`  provider: ${provider}`);
    if (provider === 'file') {
      console.log('  - fastlane/.env');
      console.log('  - android/keystore.properties (if Android configured)');
      console.log('  - secrets/ (copied key files)');
    } else {
      console.log(`  - vault: ${toPosixRelative(os.homedir(), projectVaultDir(projectRoot))}`);
      console.log('  - macOS Keychain entries for scalar secrets');
      console.log('  - fastlane/.env contains non-secret path references only');
    }
    return { configured: true, provider };
  } finally {
    process.umask(previousUmask);
  }
}

export function materializeKeychainPasswords(projectRoot: string): void {
  if (!keychainAvailable()) return;
  const service = `rn-local-release:${path.basename(projectRoot)}`;
  const storePassword = keychainGet(service, 'MYAPP_UPLOAD_STORE_PASSWORD');
  const keyPassword = keychainGet(service, 'MYAPP_UPLOAD_KEY_PASSWORD');
  const alias = keychainGet(service, 'MYAPP_UPLOAD_KEY_ALIAS');
  if (storePassword) process.env.MYAPP_UPLOAD_STORE_PASSWORD = storePassword;
  if (keyPassword) process.env.MYAPP_UPLOAD_KEY_PASSWORD = keyPassword;
  if (alias) process.env.MYAPP_UPLOAD_KEY_ALIAS = alias;
  const ascKey = keychainGet(service, 'ASC_KEY_ID');
  const ascIssuer = keychainGet(service, 'ASC_ISSUER_ID');
  if (ascKey) process.env.ASC_KEY_ID = ascKey;
  if (ascIssuer) process.env.ASC_ISSUER_ID = ascIssuer;
}

export function purgeCredentials(projectRoot: string): void {
  const service = `rn-local-release:${path.basename(projectRoot)}`;
  for (const account of [
    'ASC_KEY_ID',
    'ASC_ISSUER_ID',
    'MYAPP_UPLOAD_STORE_PASSWORD',
    'MYAPP_UPLOAD_KEY_PASSWORD',
    'MYAPP_UPLOAD_KEY_ALIAS',
  ]) {
    keychainDelete(service, account);
  }
  const vault = projectVaultDir(projectRoot);
  if (exists(vault)) {
    fs.rmSync(vault, { recursive: true, force: true });
  }
}
